"""Dev-set tasks for text2polars.

Each task is checkable WITHOUT knowing polars: you read the setup table and the
expected answer. That property is the whole reason this project is workable.

Fields:
  id           unique, stable
  category     see CATEGORIES below — results are reported per category (NOTES F3)
  instruction  what the model is asked, in plain English
  setup        the data, already defined for the model
  expected     the right answer, written independently of `solution`
  solution     a reference implementation, used ONLY to validate the task

`solution` is never shown to a model being evaluated. It exists so that
evals/validate.py can prove the task is solvable and that `expected` is right.
Because the two were written separately, disagreement means one of them is
wrong — which is exactly what we want to catch.
"""

